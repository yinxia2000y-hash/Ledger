#!/usr/bin/env node
/**
 * ledger.mjs — one portable CLI for the Ledger workflow.
 *
 * Zero dependencies. Node >= 18. No absolute paths baked in.
 *
 *   node ledger.mjs init <slug> --goal "..."
 *   node ledger.mjs add <slug> <path> --does "..." --for "..."
 *   node ledger.mjs close <slug>
 *   node ledger.mjs list [slug]
 *   node ledger.mjs sync [slug]
 *   node ledger.mjs book init <slug> --title "..." --goal "..." --ch "ch10|T|S|kw"
 *   node ledger.mjs book touch <slug> <ch> --answer "..."
 *   node ledger.mjs book find <keyword>
 *   node ledger.mjs book check <slug>
 *   node ledger.mjs book orphans [slug]
 *   node ledger.mjs book root
 *   node ledger.mjs book list [slug]
 *   node ledger.mjs artifact scan|clean|guard <slug> [--apply] [--max-mb N]
 *
 * Root resolution order: --root <dir>  >  $LEDGER_ROOT  >  ./_work
 */

import { mkdirSync, existsSync, readFileSync, writeFileSync, readdirSync, statSync, rmSync } from 'node:fs'
import { join, resolve, relative, dirname, extname } from 'node:path'

// ---------------------------------------------------------------- helpers

function parse(argv) {
  const pos = []
  const flags = {}
  const multi = {}
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (!a.startsWith('--')) { pos.push(a); continue }
    const key = a.slice(2)
    const vals = []
    while (argv[i + 1] !== undefined && !argv[i + 1].startsWith('--')) vals.push(argv[++i])
    if (key === 'ch') { (multi.ch ||= []).push(vals.join(' ')); continue }
    flags[key] = vals.length === 0 ? 'true' : vals.join(' ')
  }
  return { pos, flags, multi }
}

const die = (m) => { console.error(`[ledger] ${m}`); process.exit(1) }
const ok = (m) => console.log(`[ledger] ${m}`)
const warn = (m) => console.log(`  ! ${m}`)

function rootDir(flags) {
  if (flags.root && flags.root !== 'true') return resolve(flags.root)
  if (process.env.LEDGER_ROOT) return resolve(process.env.LEDGER_ROOT)
  return resolve(process.cwd(), '_work')
}
const slugDir = (root, slug) => join(root, slug)
const manifestOf = (root, slug) => join(slugDir(root, slug), 'MANIFEST.md')
const bookOf = (root, slug) => join(slugDir(root, slug), 'BOOK.md')

function walk(dir, base = dir) {
  let out = []
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    let st
    try { st = statSync(p) } catch { continue }
    if (st.isDirectory()) out = out.concat(walk(p, base))
    else out.push(relative(base, p).replace(/\\/g, '/'))
  }
  return out
}
const mtime = (p) => { try { return statSync(p).mtimeMs } catch { return 0 } }
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')

// ---------------------------------------------------------------- templates

const STAGES = [
  [0, '00-brief'], [10, '10-plan'], [20, '20-exec'], [30, '30-evidence'], [40, '40-deliver'],
]
function dirFor(id) {
  const n = Number(String(id).replace(/^ch/, '')) || 0
  let dir = '20-exec'
  for (const [min, name] of STAGES) if (n >= min) dir = name
  return dir
}

const STANDARD = `## Where things go

| Location | Holds |
|---|---|
| \`out/\` | Real deliverables (move out once promoted to a permanent tool) |
| \`backup/\` | Originals of any shared config you are about to change |
| \`tmp/\` | Probes and scratch. **Must be empty at close.** |
| Permanent assets | Not here. Skills go to your skills dir, tools to your tools dir. |

**Hard rules**: one task = one directory · one authoritative file (no v2/final/bak/copy) · every file must be \`add\`-ed · never edit \`node_modules\` · always \`close\`.
`

const TAIL = `## Closing three lines

\`\`\`
Authoritative artifact: <single path>
Verification: <command> -> exit 0
Cleanup: tmp cleared <N>, archived <N>, deleted <N>
\`\`\`
`

const F_BEGIN = '<!-- FILES:BEGIN -->'
const F_END = '<!-- FILES:END -->'
const C_BEGIN = '<!-- CHAPTERS:BEGIN -->'
const C_END = '<!-- CHAPTERS:END -->'
const HEAD_ROW = '| File (relative) | What it is | What it is for / who reads it | How to verify | Status |'
const HEAD_SEP = '|---|---|---|---|---|'
const CH_HEAD = '| Chapter | Title | One-line summary | Keywords | File | Status |'
const MAX_BOOK_LINES = 200

function header(slug, goal, status, root) {
  const now = new Date().toISOString().replace('T', ' ').slice(0, 19)
  return [
    `# MANIFEST — ${slug}`, '',
    '| Field | Value |', '|---|---|',
    `| Goal | ${esc(goal)} |`,
    `| Created | ${now} |`,
    `| Status | ${esc(status)} |`,
    `| Task root | \`${slugDir(root, slug)}\` |`,
    '',
    '> Generated by `ledger.mjs`. Read this first when you start; close against it when you finish.',
    '',
  ].join('\n')
}

function buildManifest(slug, goal, status, root, rows) {
  return [
    header(slug, goal, status, root), STANDARD,
    '## Files', '', F_BEGIN, HEAD_ROW, HEAD_SEP,
    ...rows, F_END, '', TAIL,
  ].join('\n')
}

function readManifest(root, slug) {
  const p = manifestOf(root, slug)
  if (!existsSync(p)) die(`no MANIFEST.md at ${p} — run "init" first`)
  const txt = readFileSync(p, 'utf8').replace(/\r\n/g, '\n')
  const goal = (/\| Goal \| (.*?) \|/.exec(txt) || [, ''])[1].replace(/\\\|/g, '|')
  const status = (/\| Status \| (.*?) \|/.exec(txt) || [, 'in progress'])[1]
  const b = txt.indexOf(F_BEGIN), e = txt.indexOf(F_END)
  if (b < 0 || e < 0) die('MANIFEST.md is missing the FILES markers (edited by hand?)')
  const rows = txt.slice(b + F_BEGIN.length, e).trim().split('\n')
    .filter(l => l.startsWith('|') && !l.startsWith('|---') && !l.includes('| File (relative) |'))
  return { goal, status, rows }
}
const writeManifest = (root, slug, goal, status, rows) =>
  writeFileSync(manifestOf(root, slug), buildManifest(slug, goal, status, root, rows), 'utf8')
const rowKey = (line) => { const m = /^\|\s*`([^`]+)`/.exec(line); return m ? m[1] : null }

// ---------------------------------------------------------------- task-dir side

function cmdInit(slug, flags) {
  if (!slug) die('usage: init <slug> --goal "..." [--expect N] [--trace] [--force]')
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) die('slug must be lower-case kebab-case')
  const root = rootDir(flags)
  if (existsSync(manifestOf(root, slug))) die(`MANIFEST.md already exists for ${slug} — use add/close, do not recreate`)

  const expect = Number(flags.expect ?? 0)
  const trace = flags.trace === 'true'
  const existing = existsSync(slugDir(root, slug))
    ? walk(slugDir(root, slug)).filter(f => f !== 'MANIFEST.md').length : 0
  if (existing === 0 && expect > 0 && expect <= 3 && !trace && flags.force !== 'true') {
    ok(`skip: ${expect} output file(s), no need for traceability`)
    console.log('  Work directly and state the artifact path in your reply.')
    console.log('  Measured: 26 of 83 ledgers were >20% of their task\'s total output. Force it with --force if you disagree.')
    return
  }

  for (const sub of ['out', 'backup', 'tmp']) mkdirSync(join(slugDir(root, slug), sub), { recursive: true })
  const row = '| `MANIFEST.md` | This task\'s file ledger and placement standard | Read first, close against it | `ledger.mjs list <slug>` | permanent |'
  writeManifest(root, slug, flags.goal || '(goal not set)', 'in progress', [row])
  ok(`init ok: ${slug}`)
  console.log(`  root: ${slugDir(root, slug)}`)
}

function cmdAdd(slug, rel, flags) {
  if (!slug || !rel) die('usage: add <slug> <relative path> --does "..." --for "..."')
  const root = rootDir(flags)
  const abs = join(slugDir(root, slug), rel)
  if (!existsSync(abs)) die(`file does not exist yet: ${abs}`)
  if (!flags.does || !flags.for) die('--does and --for are both required')
  const { goal, status, rows } = readManifest(root, slug)
  const key = rel.replace(/\\/g, '/')
  const line = `| \`${esc(key)}\` | ${esc(flags.does)} | ${esc(flags.for)} | ${esc(flags.verify || '—')} | ${esc(flags.state || 'in progress')} |`
  writeManifest(root, slug, goal, status, [...rows.filter(r => rowKey(r) !== key), line])
  ok(`add ok: ${key}`)
}

function cmdClose(slug, flags) {
  if (!slug) die('usage: close <slug>')
  const root = rootDir(flags)
  const { goal, rows } = readManifest(root, slug)
  const registered = new Set(rows.map(rowKey).filter(Boolean))
  const actual = walk(slugDir(root, slug)).filter(f => f !== 'MANIFEST.md')
  const unregistered = actual.filter(f => !registered.has(f))
  const tmpLeft = actual.filter(f => f.startsWith('tmp/'))
  writeManifest(root, slug, goal, 'done', rows)
  ok(`close: ${slug}`)
  console.log(`  registered ${registered.size} / actual ${actual.length}`)
  console.log(`  unregistered: ${unregistered.length ? unregistered.join(', ') : 'none'}`)
  console.log(`  tmp leftovers: ${tmpLeft.length ? tmpLeft.join(', ') : 'none'}`)
  if (unregistered.length || tmpLeft.length) { console.log('  FAIL — register or clear them, then close again'); process.exitCode = 1 }
  else console.log('  PASS — you may fill in the closing three lines')
}

function cmdList(slug, flags) {
  const root = rootDir(flags)
  if (slug) { process.stdout.write(readFileSync(manifestOf(root, slug), 'utf8')); return }
  if (!existsSync(root)) die(`root does not exist: ${root}`)
  const dirs = readdirSync(root).filter(d => existsSync(manifestOf(root, d)))
  ok(`${dirs.length} task(s) under ${root}`)
  for (const d of dirs) console.log(`  - ${d}`)
}

function cmdSync(slug, flags) {
  const root = rootDir(flags)
  const targets = slug ? [slug] : readdirSync(root).filter(d => existsSync(manifestOf(root, d)))
  let n = 0
  for (const s of targets) {
    const p = manifestOf(root, s)
    if (!existsSync(p)) continue
    const txt = readFileSync(p, 'utf8').replace(/\r\n/g, '\n')
    const start = txt.indexOf('## Where things go')
    const end = txt.indexOf('## Files')
    if (start < 0 || end < 0) { warn(`${s}: unrecognised MANIFEST layout, skipped`); continue }
    const cur = txt.slice(start, end)
    if (cur.trim() === STANDARD.trim()) continue
    writeFileSync(p, txt.slice(0, start) + STANDARD + '\n' + txt.slice(end), 'utf8')
    n++
    if (slug) ok(`sync: template refreshed (${cur.length} -> ${STANDARD.length} bytes)`)
  }
  if (!slug) ok(`sync done: ${n}/${targets.length} refreshed`)
}

// ---------------------------------------------------------------- book side

function parseChapters(txt) {
  const b = txt.indexOf(C_BEGIN), e = txt.indexOf(C_END)
  const block = (b >= 0 && e >= 0) ? txt.slice(b, e) : txt
  return block.split('\n')
    .filter(l => l.startsWith('| ch'))
    .map(l => {
      const c = l.split('|').map(s => s.trim())
      return { id: c[1], title: c[2], summary: c[3], keywords: c[4], file: (c[5] || '').replace(/`/g, ''), status: c[6] }
    })
}

function readBook(root, slug) {
  const p = bookOf(root, slug)
  if (!existsSync(p)) die(`no BOOK.md at ${p} — this task has no book`)
  const txt = readFileSync(p, 'utf8').replace(/\r\n/g, '\n')
  const title = (/# BOOK:\s*(.*)/.exec(txt) || [, slug])[1].trim()
  return { title, txt, chapters: parseChapters(txt) }
}

function writeChapterTable(root, slug, title, goal, chapters) {
  const p = bookOf(root, slug)
  const old = existsSync(p) ? readFileSync(p, 'utf8').replace(/\r\n/g, '\n') : ''
  const rows = chapters.map(c => `| ${c.id} | ${c.title} | ${c.summary} | ${c.keywords} | \`${c.file}\` | ${c.status} |`)
  const kw = new Map()
  for (const c of chapters) for (const k of String(c.keywords).split(',').map(s => s.trim()).filter(Boolean)) {
    if (!kw.has(k)) kw.set(k, [])
    kw.get(k).push(c.id)
  }
  const kwTable = [...kw.entries()].sort((a, b) => a[0].localeCompare(b[0]))
    .map(([k, ids]) => `- ${k} -> ${ids.join(', ')}`).join('\n')
  const body = [
    `# BOOK: ${title || slug}`, '',
    '| Field | Value |', '|---|---|',
    `| slug | \`${slug}\` |`,
    `| goal | ${esc(goal || '(not set)')} |`,
    `| authoritative conclusion | \`${chapters.find(c => c.id.startsWith('ch4'))?.file || chapters[chapters.length - 1]?.file || '—'}\` |`,
    `| status | ${chapters.every(c => c.status === 'done') ? 'done' : 'in progress'} |`,
    `| updated | ${new Date().toISOString().slice(0, 10)} |`, '',
    '## How to retrieve', '',
    'Read this file first. Use the summary and keyword columns to pick 1–2 chapters, then read only those files.',
    'This file holds no prose. If you changed a chapter body, update its summary/keywords here.',
    '**Never** grep the whole project for a conclusion — that means the book was never built or never maintained.', '',
    '## Chapters', '', C_BEGIN, CH_HEAD, '|---|---|---|---|---|---|', ...rows, C_END, '',
    '## Keyword index', '', '(maintained by hand; used to answer "which chapter should I read")', '', kwTable || '(none)', '',
    '## Registered outputs', '',
    'Files over 50MB are registered by path only, never inlined into a chapter body.', '',
    '| File | Chapter | What it is | Who reads it |', '|---|---|---|---|', '',
  ].join('\n')
  const registered = (old.match(/## Registered outputs[\s\S]*$/)?.[0] || '').split('\n').filter(l => l.startsWith('| ') && !l.includes('| File |') && !l.startsWith('|---'))
  writeFileSync(p, body + registered.join('\n') + (registered.length ? '\n' : ''), 'utf8')
}

function cmdBookInit(slug, flags, multi) {
  const root = rootDir(flags)
  if (!slug) die('usage: book init <slug> --title "..." --goal "..." --ch "ch10|Title|Summary|kw1,kw2"')
  const specs = multi.ch || []
  if (!specs.length) die('at least one --ch is required')
  const chapters = specs.map(spec => {
    const p = spec.split('|').map(s => s.trim())
    const id = p[0]
    return {
      id,
      title: p[1] || id,
      summary: p[2] || '',
      keywords: p[3] || '',
      file: p[4] || `${dirFor(id)}/${id}.md`,
      status: 'pending',
    }
  })
  writeChapterTable(root, slug, flags.title || slug, flags.goal || '', chapters)
  ok(`book init ok: ${slug}`)
  console.log(`  BOOK.md: ${bookOf(root, slug)}`)
  console.log(`  chapters: ${chapters.length}`)
}

function cmdBookAdd(slug, flags, multi) {
  const root = rootDir(flags)
  const book = readBook(root, slug)
  for (const spec of multi.ch || []) {
    const p = spec.split('|').map(s => s.trim())
    const id = p[0]
    if (book.chapters.some(c => c.id === id)) die(`chapter ${id} already exists — chapter numbers are never reused`)
    book.chapters.push({
      id, title: p[1] || id, summary: p[2] || '',
      keywords: p[3] || '', file: p[4] || `${dirFor(id)}/${id}.md`, status: 'pending',
    })
  }
  writeChapterTable(root, slug, book.title, '', book.chapters)
  ok(`book add ok: ${slug} now has ${book.chapters.length} chapters`)
}

function cmdBookTouch(slug, chId, flags) {
  const root = rootDir(flags)
  const book = readBook(root, slug)
  const c = book.chapters.find(x => x.id === chId)
  if (!c) die(`no chapter ${chId} in BOOK.md`)
  const abs = join(slugDir(root, slug), c.file)
  if (existsSync(abs)) die(`chapter file already exists, edit it instead of recreating: ${abs}`)
  mkdirSync(dirname(abs), { recursive: true })
  writeFileSync(abs, [
    `# ${c.id} ${c.title}`, '',
    '## What this chapter must answer', '',
    flags.answer || '(fill in)', '',
    '## Body', '', '(pending)', '',
    '## Outputs from this chapter', '',
    '| File (relative to task root) | What it is | Who reads it |', '|---|---|---|', '',
  ].join('\n') + '\n', 'utf8')
  c.status = 'writing'
  writeChapterTable(root, slug, book.title, '', book.chapters)
  ok(`touch ok: ${c.id}`)
  console.log(`  ${abs}`)
}

function cmdBookFind(kw, flags) {
  const root = rootDir(flags)
  if (!existsSync(root)) die(`root does not exist: ${root}`)
  const hits = []
  for (const d of readdirSync(root)) {
    const bp = bookOf(root, d)
    if (!existsSync(bp)) continue
    for (const l of readFileSync(bp, 'utf8').replace(/\r\n/g, '\n').split('\n')) {
      if (!l.startsWith('| ch')) continue
      if (!kw || l.toLowerCase().includes(String(kw).toLowerCase())) hits.push({ slug: d, line: l })
    }
  }
  if (!hits.length) {
    ok(`no hit for "${kw}". Zero hits means "not found", not an error.`)
    console.log('  Next: build the missing book, or grep inside 20-exec/ and 30-evidence/ only.')
    return
  }
  const bySlug = new Map()
  for (const h of hits) (bySlug.get(h.slug) ?? bySlug.set(h.slug, []).get(h.slug)).push(h.line)
  ok(`${hits.length} chapter(s) across ${bySlug.size} book(s)`)
  for (const [s, ls] of bySlug) {
    console.log(`\n## ${s}`)
    for (const l of ls) console.log('  ' + l)
  }
  console.log('\n>> Read only the chapter bodies you hit. Do not scan directories.')
}

function cmdBookCheck(slug, flags) {
  const root = rootDir(flags)
  const book = readBook(root, slug)
  const base = slugDir(root, slug)
  let bad = 0

  const ids = book.chapters.map(c => c.id)
  if (new Set(ids).size !== ids.length) { console.log('FAIL duplicate chapter number'); bad++ }

  for (const c of book.chapters) {
    const abs = join(base, c.file)
    if (!existsSync(abs)) { if (c.status !== 'pending') { console.log(`FAIL ${c.id} status=${c.status} but file is missing: ${c.file}`); bad++ } }
    else if (c.status === 'pending') warn(`${c.id} file exists but status is still pending`)
  }
  for (const c of book.chapters) if (c.summary.length > 60) warn(`${c.id} summary is ${c.summary.length} chars (>60) — the responsibility is unclear, consider splitting`)

  const EXEMPT = new Set(['MANIFEST.md', 'BOOK.md'])
  const files = walk(base).filter(f => !EXEMPT.has(f) && !f.startsWith('tmp/') && !f.startsWith('backup/'))
  const declared = new Set(book.chapters.map(c => c.file))
  const orphan = files.filter(f => {
    if (declared.has(f)) return false
    return !book.txt.includes('| ' + f + ' |') && !book.txt.includes('`' + f + '`')
  })
  for (const f of orphan) { console.log(`FAIL output not attached to any chapter: ${f}`); bad++ }

  const lines = book.txt.split('\n').length
  if (lines > MAX_BOOK_LINES) { console.log(`FAIL BOOK.md is ${lines} lines (>${MAX_BOOK_LINES})`); bad++ }

  const bm = mtime(bookOf(root, slug))
  let stale = 0
  for (const c of book.chapters) {
    const abs = join(base, c.file)
    if (existsSync(abs) && mtime(abs) > bm + 1000) { stale++; warn(`${c.id} is newer than BOOK.md — its summary/keywords may be out of date`) }
  }

  const mf = manifestOf(root, slug)
  let cross = 0
  if (existsSync(mf)) {
    const t = readFileSync(mf, 'utf8').replace(/\r\n/g, '\n')
    const b = t.indexOf(F_BEGIN), e = t.indexOf(F_END)
    if (b >= 0 && e >= 0) {
      const regs = t.slice(b, e).split('\n').map(rowKey).filter(Boolean)
        .filter(p => p !== 'MANIFEST.md' && p !== 'BOOK.md' && !p.startsWith('tmp/') && !p.startsWith('backup/'))
      for (const p of regs) {
        if (!declared.has(p) && !book.txt.includes('`' + p + '`') && !book.txt.includes('| ' + p + ' |')) {
          cross++; warn(`${p} is registered in MANIFEST.md but not attached to any chapter`)
        }
      }
    }
  }

  ok(`book check: ${slug}`)
  console.log(`  chapters ${book.chapters.length} / files ${files.length} / orphans ${orphan.length} / problems ${bad}`)
  if (stale) console.log(`  ${stale} chapter(s) newer than the index`)
  if (cross) console.log(`  ${cross} file(s) in MANIFEST but not in BOOK`)
  if (bad === 0) console.log('  PASS')
  else process.exitCode = 1
}

function cmdBookOrphans(slug, flags) {
  const root = rootDir(flags)
  const targets = slug ? [slug] : readdirSync(root).filter(d => existsSync(manifestOf(root, d)))
  const EXEMPT = new Set(['MANIFEST.md', 'BOOK.md'])
  let total = 0, scanned = 0
  for (const s of targets) {
    const base = slugDir(root, s)
    if (!existsSync(base)) continue
    if (!existsSync(manifestOf(root, s))) { warn(`${s}: no MANIFEST.md, cannot judge`); continue }
    const { rows } = readManifest(root, s)
    const registered = new Set(rows.map(rowKey).filter(Boolean).map(p => p.replace(/\\/g, '/')))
    const files = walk(base).filter(f => !EXEMPT.has(f) && !f.startsWith('tmp/') && !f.startsWith('backup/'))
    const orphan = files.filter(f => !registered.has(f))
    scanned++
    if (orphan.length) {
      total += orphan.length
      console.log(`FAIL ${s}: ${orphan.length} unregistered file(s)`)
      for (const f of orphan.slice(0, 6)) console.log(`    - ${f}`)
      if (orphan.length > 6) console.log(`    ... and ${orphan.length - 6} more`)
    }
  }
  ok(`book orphans: scanned ${scanned} task(s), unregistered ${total}`)
  if (total === 0) console.log('  PASS')
  else { console.log('  >> Register them with: add <slug> <path> --does --for'); process.exitCode = 1 }
}

function cmdBookRoot(flags) {
  const root = rootDir(flags)
  if (!existsSync(root)) die(`root does not exist: ${root}`)
  const entries = readdirSync(root)
  const loose = entries.filter(n => { try { return !statSync(join(root, n)).isDirectory() } catch { return false } })
  const dirs = entries.filter(n => { try { return statSync(join(root, n)).isDirectory() } catch { return false } })
  const noManifest = dirs.filter(d => !existsSync(manifestOf(root, d)))
  ok(`book root: ${root}`)
  console.log(`  task dirs ${dirs.length} / missing MANIFEST.md ${noManifest.length}`)
  if (loose.length) {
    console.log(`  FAIL ${loose.length} loose file(s) at the root — move them into a task dir first:`)
    for (const f of loose) console.log(`    - ${f}`)
    process.exitCode = 1
  } else console.log('  PASS — root holds only task directories')
  if (noManifest.length) for (const d of noManifest.slice(0, 20)) warn(`${d}: no MANIFEST.md`)
}

function cmdBookList(slug, flags) {
  const root = rootDir(flags)
  if (slug) { process.stdout.write(readFileSync(bookOf(root, slug), 'utf8')); return }
  const dirs = readdirSync(root).filter(d => existsSync(bookOf(root, d)))
  ok(`${dirs.length} book(s)`)
  for (const d of dirs) console.log(`  - ${d}`)
}

// ---------------------------------------------------------------- artifact side

const BUILD_EXT = new Set(['.apk', '.ipa', '.dex', '.class', '.so', '.dll', '.dylib', '.o', '.obj', '.exe', '.zip', '.tar', '.gz', '.xz', '.img', '.iso', '.bin'])
const LOG_EXT = new Set(['.log', '.txt', '.tmp', '.dump', '.jsonl'])
const ASSET_HINT = /(keyframe|kf\d|contact[-_]?sheet|storyboard|reference|refsheet)/i
const SHOT_HINT = /(screen|shot|capture|cap\d|screenshot|exc|now)/i
const ASSET_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.bmp', '.svg'])

function classify(rel) {
  const ext = extname(rel).toLowerCase()
  const name = rel.split('/').pop()
  // `backup/` holds the originals of files you changed, for rollback. Nothing there is
  // disposable: deleting a `.orig` breaks the rollback path, which is the whole point of
  // keeping the directory. `book check`, `book orphans` and `book root` all exempt it;
  // this classifier must agree, or the gates disagree about what "safe to delete" means.
  if (rel.startsWith('backup/')) return { cls: 'backup', keep: true, why: 'rollback original — never delete' }
  if (ext === '.md') return { cls: 'report', keep: true, why: 'a report is the conclusion carrier — always keep' }
  if (ASSET_EXT.has(ext)) {
    if (ASSET_HINT.test(name)) return { cls: 'image-asset', keep: true, why: 'named like a deliverable asset (keyframe / reference / contact sheet)' }
    if (SHOT_HINT.test(name) || rel.startsWith('tmp/')) return { cls: 'image-shot', keep: false, why: 'analysis screenshot — keep the data, drop the image' }
    return { cls: 'image-unknown', keep: true, why: 'unrecognised image — kept conservatively' }
  }
  if (BUILD_EXT.has(ext)) return { cls: 'build', keep: false, why: 'regenerable build artifact' }
  if (LOG_EXT.has(ext)) return { cls: 'process', keep: false, why: 'process material' }
  return { cls: 'other', keep: true, why: 'unclassified — kept conservatively' }
}

function cmdArtifact(sub, slug, flags) {
  const root = rootDir(flags)
  if (!slug) die(`usage: artifact ${sub} <slug> [--apply] [--max-mb N]`)
  const base = slugDir(root, slug)
  if (!existsSync(base)) die(`no such task: ${base}`)
  const files = walk(base).map(rel => ({ rel, abs: join(base, rel), ...classify(rel) }))
  const total = files.reduce((s, f) => s + (statSync(f.abs).size || 0), 0)
  const kb = (n) => (n / 1024).toFixed(1) + 'KB'

  if (sub === 'scan') {
    ok(`artifact scan: ${slug}`)
    console.log(`  ${files.length} files / ${kb(total)}`)
    const byCls = new Map()
    for (const f of files) byCls.set(f.cls, (byCls.get(f.cls) || 0) + 1)
    for (const [c, n] of byCls) console.log(`    ${c}: ${n}`)
    const droppable = files.filter(f => !f.keep)
    console.log(`  droppable under current rules: ${droppable.length} / ${kb(droppable.reduce((s, f) => s + statSync(f.abs).size, 0))}`)
    return
  }

  if (sub === 'guard') {
    const max = Number(flags['max-mb'] ?? 200) * 1024 * 1024
    ok(`artifact guard: ${slug}`)
    console.log(`  ${files.length} files / ${kb(total)}  budget ${flags['max-mb'] ?? 200}MB`)
    if (total > max) { console.log(`  FAIL over budget by ${kb(total - max)}`); process.exitCode = 1 }
    else console.log('  PASS — within budget')
    return
  }

  if (sub === 'clean') {
    const apply = flags.apply === 'true'
    const drop = files.filter(f => !f.keep)
    ok(`artifact clean: ${slug}`)
    console.log(`  mode: ${apply ? 'APPLY' : 'DRY-RUN (add --apply to execute)'}`)
    console.log(`  would remove ${drop.length} file(s) / ${kb(drop.reduce((s, f) => s + statSync(f.abs).size, 0))}`)
    for (const f of drop) {
      console.log(`    - ${f.rel}  ${kb(statSync(f.abs).size)}  [${f.cls}] ${f.why}`)
      if (apply) rmSync(f.abs, { force: true })
    }
    const kept = files.filter(f => f.keep)
    console.log(`  kept ${kept.length} file(s)`)
    for (const f of kept) console.log(`    + ${f.rel}  ${kb(statSync(f.abs).size)}  (${f.why})`)
    return
  }

  if (sub === 'report') {
    const lines = ['| File | Class | Kept | Size | Reason |', '|---|---|---|---|---|']
    for (const f of files) lines.push(`| \`${f.rel}\` | ${f.cls} | ${f.keep ? 'yes' : 'no'} | ${kb(statSync(f.abs).size)} | ${f.why} |`)
    console.log(lines.join('\n'))
    return
  }

  die(`unknown artifact subcommand: ${sub}`)
}

// ---------------------------------------------------------------- dispatch

const argv = process.argv.slice(2)
if (!argv.length || argv[0] === '--help' || argv[0] === '-h') {
  console.log(`ledger.mjs — file ledger + chapter book + artifact retention

  init <slug> --goal "..." [--expect N] [--trace] [--force]
  add <slug> <path> --does "..." --for "..." [--verify "..."] [--state "..."]
  close <slug>
  list [slug]
  sync [slug]

  book init <slug> --title "..." --goal "..." --ch "ch10|Title|Summary|kw1,kw2"
  book add <slug> --ch "ch11|Title|Summary|kw"
  book touch <slug> <ch> --answer "..."
  book find <keyword>
  book check <slug>
  book orphans [slug]
  book root
  book list [slug]

  artifact scan|clean|report|guard <slug> [--apply] [--max-mb N]

Global: --root <dir>   (default: $LEDGER_ROOT or ./_work)`)
  process.exit(0)
}

const { pos, flags, multi } = parse(argv)
const [cmd, ...rest] = pos

switch (cmd) {
  case 'init': cmdInit(rest[0], flags); break
  case 'add': cmdAdd(rest[0], rest[1], flags); break
  case 'close': cmdClose(rest[0], flags); break
  case 'list': cmdList(rest[0], flags); break
  case 'sync': cmdSync(rest[0], flags); break
  case 'book': {
    const sub = rest[0]
    if (sub === 'init') cmdBookInit(rest[1], flags, multi)
    else if (sub === 'add') cmdBookAdd(rest[1], flags, multi)
    else if (sub === 'touch') cmdBookTouch(rest[1], rest[2], flags)
    else if (sub === 'find') cmdBookFind(rest[1], flags)
    else if (sub === 'check') cmdBookCheck(rest[1], flags)
    else if (sub === 'orphans') cmdBookOrphans(rest[1], flags)
    else if (sub === 'root') cmdBookRoot(flags)
    else if (sub === 'list') cmdBookList(rest[1], flags)
    else die(`unknown book subcommand: ${sub}`)
    break
  }
  case 'artifact': cmdArtifact(rest[0], rest[1], flags); break
  default: die(`unknown command: ${cmd} (try --help)`)
}
